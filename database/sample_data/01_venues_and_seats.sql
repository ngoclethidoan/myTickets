-- ==========================================================
-- SAMPLE DATA 1/2 : five venues and their numbered seats
--
-- Only for a NEW, EMPTY database. If the venue table already has rows this script
-- inserts nothing, so running it by accident on a live database is harmless.
-- Run it in the MAIN database (myv_myTickets), after install_all.sql.
--
-- The venue names match VENUE_ZONES in web/app.py and the map files in web/templates/maps/.
-- STANDING has no rows here: standing "seats" are virtual and are created per event
-- by trg_ticket_bi, up to event.standing_capacity.
-- seat_id (SE0001, SE0002, ...) is generated by trg_seat_bi.
-- ==========================================================
SET NAMES utf8mb4;   -- this file contains Vietnamese text
USE myv_myTickets;

SET @fresh := (SELECT COUNT(*) = 0 FROM venue);

INSERT INTO venue (venue_id, address, capacity)
SELECT v.venue_id, v.address, v.capacity
  FROM (SELECT 'VE01' AS venue_id, 'The Velvet Room' AS address, 320 AS capacity
        UNION ALL SELECT 'VE02', 'Lantern Hall',       216
        UNION ALL SELECT 'VE03', 'Starlight Theatre',  286
        UNION ALL SELECT 'VE04', 'Aurora Arena',      1100
        UNION ALL SELECT 'VE05', 'Skyline Dome',      2220) v
 WHERE @fresh;

-- One line per zone: how many rows it has and how many seats per row.
-- Rows are lettered A, B, C, ...; seats are numbered 1, 2, 3, ... inside a row.
INSERT INTO seat (seat_id, venue_id, seat_zone, seat_row, seat_number)
WITH RECURSIVE n AS (
  SELECT 1 AS i
  UNION ALL
  SELECT i + 1 FROM n WHERE i < 30
),
layout AS (
            SELECT 'VE01' AS venue_id, 'VIP' AS seat_zone, 2 AS n_rows, 10 AS per_row, 1 AS zone_order
  UNION ALL SELECT 'VE01', 'A',        4, 12, 2
  UNION ALL SELECT 'VE02', 'VIP',      3, 12, 1
  UNION ALL SELECT 'VE02', 'A',        6, 14, 2
  UNION ALL SELECT 'VE02', 'B',        6, 16, 3
  UNION ALL SELECT 'VE03', 'SKYBOX',   2,  6, 1
  UNION ALL SELECT 'VE03', 'VIP',      4, 14, 2
  UNION ALL SELECT 'VE03', 'A',        8, 16, 3
  UNION ALL SELECT 'VE03', 'BALCONY',  5, 18, 4
  UNION ALL SELECT 'VE04', 'SKYBOX',   2,  8, 1
  UNION ALL SELECT 'VE04', 'VIP',      5, 16, 2
  UNION ALL SELECT 'VE04', 'A',        8, 20, 3
  UNION ALL SELECT 'VE04', 'B',       10, 24, 4
  UNION ALL SELECT 'VE05', 'SKYBOX',   2, 10, 1
  UNION ALL SELECT 'VE05', 'VIP',      6, 20, 2
  UNION ALL SELECT 'VE05', 'A',       10, 24, 3
  UNION ALL SELECT 'VE05', 'B',       12, 28, 4
)
SELECT NULL, l.venue_id, l.seat_zone, CHAR(64 + r.i USING utf8mb4), s.i
  FROM layout l
  JOIN n r ON r.i <= l.n_rows
  JOIN n s ON s.i <= l.per_row
 WHERE @fresh
 ORDER BY l.venue_id, l.zone_order, r.i, s.i;

-- Check: seats per venue and zone
SELECT v.venue_id, v.address, s.seat_zone, COUNT(*) AS seats
  FROM venue v JOIN seat s ON s.venue_id = v.venue_id
 GROUP BY v.venue_id, v.address, s.seat_zone
 ORDER BY v.venue_id, s.seat_zone;
