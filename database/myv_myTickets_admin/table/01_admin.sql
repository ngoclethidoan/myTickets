USE myv_myTickets_admin;

-- Admin accounts. They live in the admin database, separate from customers,
-- so each admin has their own username and password here.
CREATE TABLE IF NOT EXISTS admin (
  admin_id   VARCHAR(20)  NOT NULL,                              -- AD0001, AD0002, ... (generated by a trigger later)
  username   VARCHAR(50)  NOT NULL,
  password   VARCHAR(255) NOT NULL,                              -- store a hash, never the plain text
  `level`    ENUM('staff', 'super_admin') NOT NULL DEFAULT 'staff',
  PRIMARY KEY (admin_id),
  UNIQUE KEY uq_admin_username (username)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
