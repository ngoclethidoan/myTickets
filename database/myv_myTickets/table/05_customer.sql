-- Customers. A customer logs in with their own username and password.
-- Admins are NOT stored here: they live in the separate admin database.
CREATE TABLE IF NOT EXISTS customer (
  customer_id VARCHAR(20)  NOT NULL,                             -- CU0001, CU0002, ... (generated by trg_customer_bi)
  username    VARCHAR(50)  NOT NULL,
  password    VARCHAR(255) NOT NULL,                             -- store a hash, never the plain text
  name        VARCHAR(100) NOT NULL,
  email       VARCHAR(100) NOT NULL,
  phone_num   VARCHAR(20)  NULL,
  PRIMARY KEY (customer_id),
  UNIQUE KEY uq_customer_username (username),
  UNIQUE KEY uq_customer_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
