"""Glue the single .sql files into scripts that can be run in one go.

    python build_install.py

Writes two files next to this script:

  install_all.sql          a NEW installation: both databases, every table, function, view,
                           trigger, procedure and the scheduled event, in an order that works.
  upgrade_existing_db.sql  for a database that is already running: only the objects that were
                           added later, plus their GRANT lines.

Both are generated. Edit the single files in myv_myTickets/ and myv_myTickets_admin/,
then run this script again. Do not edit the two output files by hand.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAIN = "myv_myTickets"
ADMIN = "myv_myTickets_admin"

# (database, folder inside it). The order matters:
#   admin tables first (trg_customer_bi in the main database looks into admin.admin),
#   tables before views, triggers and procedures, and the scheduled event last.
INSTALL_ORDER = [
    (ADMIN, "table"),
    (MAIN, "table"),
    (MAIN, "function"),
    (MAIN, "view"),
    (MAIN, "trigger"),
    (MAIN, "procedure"),
    (MAIN, "."),          # ev_expire_orders.sql
    (ADMIN, "trigger"),
    (ADMIN, "procedure"),
]

# Objects added after the first release, with the grants they need.
UPGRADE_FILES = [
    (MAIN, "function/fn_standing_left.sql"),
    (MAIN, "procedure/pc_update_customer.sql"),
    (ADMIN, "procedure/pc_update_event.sql"),
]
UPGRADE_GRANTS = [
    "GRANT EXECUTE ON FUNCTION  myv_myTickets.fn_standing_left   TO 'customer_app'@'%';",
    "GRANT EXECUTE ON PROCEDURE myv_myTickets.pc_update_customer TO 'customer_app'@'%';",
    "GRANT EXECUTE ON PROCEDURE myv_myTickets_admin.pc_update_event TO 'admin_app'@'%';",
]

LINE = "-- " + "=" * 58


def block(database, path):
    """One source file, with a banner and the right USE in front of it."""
    rel = path.relative_to(HERE).as_posix()
    return "\n".join([LINE, "-- " + rel, LINE, "USE %s;" % database, "", path.read_text(encoding="utf-8").strip(), ""])


def build_install():
    parts = [
        LINE,
        "-- install_all.sql : build both MyTickets databases from nothing.",
        "-- GENERATED by build_install.py from the single files. Do not edit by hand.",
        "--",
        "-- Run it as the owner account (avnadmin on Aiven), as one script.",
        "-- Afterwards: 1) edit the two CHANGE_ME passwords in",
        "--                myv_myTickets_admin/grant/00_accounts_and_grants.sql and run it,",
        "--             2) optional: run sample_data/01_venues_and_seats.sql and 02_events.sql.",
        "--",
        "-- Safe to run again: tables use IF NOT EXISTS, everything else is dropped and recreated.",
        "-- BUT dropping a procedure or function also drops its grants, so after running this",
        "-- on a database that is already in use, run 00_accounts_and_grants.sql again.",
        LINE,
        "SET NAMES utf8mb4;",
        "CREATE DATABASE IF NOT EXISTS %s CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;" % MAIN,
        "CREATE DATABASE IF NOT EXISTS %s CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;" % ADMIN,
        "",
    ]
    for database, folder in INSTALL_ORDER:
        for path in sorted((HERE / database / folder).glob("*.sql")):
            parts.append(block(database, path))
    parts += [LINE, "-- Done. Next: grants, then (optional) sample data.", LINE, ""]
    return "\n".join(parts)


def build_upgrade():
    parts = [
        LINE,
        "-- upgrade_existing_db.sql : add the newer objects to a database that is already running.",
        "-- GENERATED by build_install.py from the single files. Do not edit by hand.",
        "--",
        "-- Run it once as the owner account (avnadmin on Aiven), as one script.",
        "-- It only ADDS one function and two procedures and grants EXECUTE on them.",
        "-- No table, no data and no existing procedure is changed.",
        "--   fn_standing_left     standing tickets left, shown on the event page",
        "--   pc_update_customer   lets a customer edit the profile and change the password",
        "--   pc_update_event      lets a super admin edit an event",
        "-- Until this script has run, the web app still works; those three features are just switched off.",
        LINE,
        "",
    ]
    for database, rel in UPGRADE_FILES:
        parts.append(block(database, HERE / database / rel))
    parts += [LINE, "-- grants for the new objects", LINE] + UPGRADE_GRANTS + [""]
    return "\n".join(parts)


def main():
    for name, text in (("install_all.sql", build_install()), ("upgrade_existing_db.sql", build_upgrade())):
        (HERE / name).write_text(text, encoding="utf-8", newline="\n")
        print("wrote %s (%d lines)" % (name, text.count("\n")))


if __name__ == "__main__":
    main()
